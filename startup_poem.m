function startup_poem()
% STARTUP_POEM Add POEM source, benchmark, example, and test folders to the MATLAB path.
%
% Inputs:
%   None
%
% Outputs:
%   None

    root_dir = fileparts(mfilename('fullpath'));
    folders = { ...
        fullfile(root_dir, 'src'), ...
        fullfile(root_dir, 'src', 'core'), ...
        fullfile(root_dir, 'src', 'sensing'), ...
        fullfile(root_dir, 'src', 'utils'), ...
        fullfile(root_dir, 'synthetic'), ...
        fullfile(root_dir, 'realdata', 'deepmimo'), ...
        fullfile(root_dir, 'realdata', 'smlm'), ...
        fullfile(root_dir, 'examples'), ...
        fullfile(root_dir, 'tests') ...
    };
    for i = 1:numel(folders)
        if isfolder(folders{i})
            addpath(folders{i});
        end
    end
end
